def run_bank_forms(bank: str, forms: Iterable[dict], dry_run: bool = False) -> int:
    bank = canonical_bank(bank)
    if not bank:
        raise RouteError("未识别付款银行")
    form_list = list(forms)
    if not form_list:
        print(f"[跳过] {bank} 队列为空")
        return 0
    dispatch = {
        "招商银行": run_cmb,
        "兴业银行": run_cib,
        "中国农业银行": run_abc,
        "中国银行": run_boc,
    }
    return dispatch[bank](form_list, dry_run)


def parse_bank_option(value: str) -> str:
    bank = canonical_bank(value)
    if not bank:
        raise argparse.ArgumentTypeError(f"不支持的银行: {value}")
    return bank


def run_single_cli(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="运行最新或指定 JSON 对应的单笔银行制单程序")
    parser.add_argument("json_path", nargs="?", help="单笔 bank_form JSON；不填则使用 latest_route/bank_form")
    parser.add_argument("--bank", type=parse_bank_option, help="手动指定付款银行")
    parser.add_argument("--dry-run", action="store_true", help="只检查和打印，不启动银行程序")
    args = parser.parse_args(argv)

    try:
        form, source = load_single_form(args.json_path)
        bank = args.bank or canonical_bank(form.get("付款银行") or form.get("付款银行原文"))
        normalized = normalize_form(form, bank)
        print(f"数据来源: {source}")
        print(f"付款银行: {normalized['付款银行']}")
        print(f"业务参考号: {normalized.get('业务参考号')}")
        return run_bank_forms(normalized["付款银行"], [normalized], dry_run=args.dry_run)
    except (RouteError, OSError, json.JSONDecodeError) as exc:
        print(f"[终止] {exc}")
        return 2


def run_batch_cli(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="按 bank_batches 中的队列运行银行制单程序")
    parser.add_argument("--bank", "-b", type=parse_bank_option, action="append", help="只运行指定银行，可重复")
    parser.add_argument("--all", action="store_true", help="运行所有非空银行队列")
    parser.add_argument("--limit", type=int, default=0, help="每家银行最多运行前 N 笔，0 表示不限制")
    parser.add_argument("--dry-run", action="store_true", help="只检查和打印，不启动银行程序")
    args = parser.parse_args(argv)

    banks = args.bank or list(BANK_QUEUE_FILES)
    if not args.bank and not args.all:
        print("未指定 --bank，默认扫描所有非空银行队列。")

    try:
        failed = False
        for bank in banks:
            forms = load_bank_queue(bank)
            if args.limit > 0:
                forms = forms[: args.limit]
            if not forms:
                print(f"[跳过] {bank} 队列为空: {queue_path_for_bank(bank)}")
                continue
            print(f"\n准备运行 {bank}: {len(forms)} 笔，队列 {queue_path_for_bank(bank)}")
            code = run_bank_forms(bank, forms, dry_run=args.dry_run)
            if code != 0:
                print(f"[失败] {bank} 退出码: {code}")
                failed = True
                break
        return 1 if failed else 0
    except (RouteError, OSError, json.JSONDecodeError) as exc:
        print(f"[终止] {exc}")
        return 2
