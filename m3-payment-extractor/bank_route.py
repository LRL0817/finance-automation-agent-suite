def run_process(
    args: list[str],
    cwd: Path,
    env: dict[str, str],
    dry_run: bool,
    *,
    report_errors: bool = True,
    bank: str = "",
) -> int:
    display_args = []
    for arg in args:
        text = str(arg)
        if "\n" in text:
            display_args.append("<inline-python>")
        elif len(text) > 180:
            display_args.append(text[:177] + "...")
        else:
            display_args.append(text)
    cmd_summary = " ".join(display_args)
    print(f"工作目录: {cwd}")
    print("启动命令:", cmd_summary)
    if dry_run:
        print("[dry-run] 未启动银行程序。")
        return 0
    if bank_invocation_disabled():
        canonical = canonical_bank(bank) or bank or "未知银行"
        print(
            f"[安全阻断] M3_DISABLE_BANK_INVOCATION=1，禁止启动真实银行子进程。\n"
            f"        银行: {canonical}\n"
            f"        工作目录: {cwd}\n"
            f"        命令摘要: {cmd_summary}\n"
            f"        退出码: {BANK_ROUTE_INVOCATION_DISABLED_EXIT_CODE}（安全阻断，非业务退出码）"
        )
        return BANK_ROUTE_INVOCATION_DISABLED_EXIT_CODE
    timeout = bank_route_process_timeout()
    if timeout is not None:
        print(f"[守护] 银行子流程超时上限: {timeout:.0f}s（BANK_ROUTE_PROCESS_TIMEOUT_SECONDS）")

    # 全局银行自动化锁：与"来参缘定时调拨"互斥。dry-run / M3_DISABLE_BANK_INVOCATION
    # 已在上面的早退路径里跳过这里，所以现在站在"将要真启动银行子进程"的位置。
    canonical_bank_name = canonical_bank(bank) or bank or "未知银行"
    global_lock_mod = _global_bank_lock_module()
    holds_global_lock = False
    if global_lock_mod is None:
        print(
            "[全局锁][fail-closed] 未找到 财务\\公共\\locks\\bank_automation_lock 模块；"
            f"无法与来参缘定时调拨互斥，不启动 {canonical_bank_name} 子进程。\n"
            f"        退出码: {BANK_ROUTE_GLOBAL_LOCK_BUSY_EXIT_CODE}（全局锁不可用，非业务退出码）"
        )
        return BANK_ROUTE_GLOBAL_LOCK_BUSY_EXIT_CODE
    else:
        try:
            g_action, g_prev = global_lock_mod.acquire(
                owner=global_lock_mod.OWNER_M3_BANK_ROUTE,
                purpose=f"M3银行制单路由 / {canonical_bank_name}",
                run_dir=str(cwd),
            )
        except global_lock_mod.LockBusy as exc:
            print(
                "[全局锁][fail-closed] 全局银行自动化锁被另一个 owner 持有，"
                f"不启动 {canonical_bank_name} 子进程。\n"
                f"        现有 owner: {exc.prev}\n"
                f"        退出码: {BANK_ROUTE_GLOBAL_LOCK_BUSY_EXIT_CODE}（全局锁忙，非业务退出码）"
            )
            return BANK_ROUTE_GLOBAL_LOCK_BUSY_EXIT_CODE
        except global_lock_mod.LockTakeoverFailed as exc:
            print(
                f"[全局锁][fail-closed] stale 全局锁接管失败：{exc}；"
                f"不启动 {canonical_bank_name} 子进程"
            )
            return BANK_ROUTE_GLOBAL_LOCK_BUSY_EXIT_CODE
        else:
            holds_global_lock = True
            if g_action == "stole_stale":
                print(f"[全局锁] 检测到 stale 全局锁并已清理：prev={g_prev}")
            else:
                print(f"[全局锁] 已获取全局银行自动化锁（owner=m3_bank_route）")

    try:
        try:
            completed = subprocess.run(
                wrap_with_gateway(args, cwd, report_errors=report_errors),
                cwd=str(cwd),
                env=env,
                check=False,
                timeout=timeout,
            )
            return int(completed.returncode)
        except subprocess.TimeoutExpired:
            # 子进程已被 subprocess 杀掉（含网关包装层）；银行 GUI/浏览器可能仍
            # 残留，交由对应银行清理函数按命令行/窗口标题收尾。返回固定超时码
            # 124（区别于业务退出码），由上层既有路由规则决定是否重试，
            # 本层不扩大重试、不在超时后盲目重跑可能已提交的制单。
            canonical = canonical_bank(bank) or bank or "未知银行"
            print(
                f"[守护][超时] {canonical} 子流程超过 {timeout:.0f}s 未结束，已强制结束子进程。\n"
                f"        工作目录: {cwd}\n"
                f"        命令摘要: {cmd_summary}\n"
                f"        超时秒数: {timeout:.0f}（BANK_ROUTE_PROCESS_TIMEOUT_SECONDS）\n"
                f"        退出码: {BANK_ROUTE_TIMEOUT_EXIT_CODE}（超时，非业务退出码）"
            )
            cleanup_after_timeout(bank)
            return BANK_ROUTE_TIMEOUT_EXIT_CODE
    finally:
        # 仅释放本进程持有的全局银行自动化锁；owner/pid 不匹配的不动。
        if holds_global_lock and global_lock_mod is not None:
            try:
                if global_lock_mod.release(owner=global_lock_mod.OWNER_M3_BANK_ROUTE):
                    print("[全局锁] 已释放全局银行自动化锁（owner=m3_bank_route）")
                else:
                    print(
                        "[全局锁] 释放全局银行自动化锁 noop（锁文件不属于本进程或已被外部清理）"
                    )
            except Exception as exc:  # noqa: BLE001
                print(f"[全局锁] 释放过程中出现异常（忽略，不掩盖主流程退出码）：{type(exc).__name__}: {exc}")


