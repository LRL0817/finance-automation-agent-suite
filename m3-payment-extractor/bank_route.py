def load_bank_queue(bank: str) -> list[dict]:
    path = queue_path_for_bank(bank)
    if not path.exists():
        legacy_path = LEGACY_BANK_BATCH_DIR / BANK_QUEUE_FILES[bank]
        if legacy_path.exists():
            path = legacy_path
    if not path.exists():
        return []
    payload = read_json(path)
    if isinstance(payload, dict):
        payload = [payload]
    if not isinstance(payload, list):
        raise RouteError(f"银行队列 JSON 必须是数组或对象: {path}")
    result = []
    for index, item in enumerate(payload, start=1):
        if not isinstance(item, dict):
            raise RouteError(f"{path} 第 {index} 条不是对象")
        result.append(item)
    return result


