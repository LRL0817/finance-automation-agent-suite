class RouteError(RuntimeError):
    """A fail-closed routing error before any bank program is opened."""


def compact(value: object) -> str:
    return "".join(str(value or "").split())


def canonical_bank(value: object) -> str:
    text = compact(value)
    if not text:
        return ""
    upper_text = text.upper()
    for bank_name, aliases in BANK_ALIASES.items():
        for alias in aliases:
            if compact(alias).upper() in upper_text:
                return bank_name
    return ""


def python_exe() -> str:
    configured = os.getenv("BANK_ROUTE_PYTHON", "").strip()
    if configured:
        return configured
    local_appdata = os.getenv("LOCALAPPDATA", "")
    py312 = Path(local_appdata) / "Programs" / "Python" / "Python312" / "python.exe"
    if py312.exists():
        return str(py312)
    return sys.executable


def truthy_env(name: str, default: bool = True) -> bool:
    raw = os.getenv(name)
    if raw is None:
        return default
    return raw.strip().lower() not in {"0", "false", "no", "off"}


def env_float(name: str, default: float) -> float:
    raw = os.getenv(name, "").strip()
    if not raw:
        return default
    try:
        return float(raw)
    except ValueError:
        return default


