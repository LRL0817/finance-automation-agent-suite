def describe_exit_code(bank: str, code: object, *, dry_run: bool = False) -> str:
    try:
        code_int = int(code)
    except (TypeError, ValueError):
        return ""
    if code_int == 0:
        return ""
    bank_name = canonical_bank(bank) or str(bank or "未知银行")
    if code_int == BANK_ROUTE_INVOCATION_DISABLED_EXIT_CODE:
        return (
            f"安全开关阻断：M3_DISABLE_BANK_INVOCATION=1，未启动 {bank_name} 子进程"
            f"（退出码 {code_int}）"
        )
    if code_int == BANK_ROUTE_TIMEOUT_EXIT_CODE:
        return f"{bank_name} 子流程超时被强制结束（退出码 {code_int}，非业务退出码）"
    if code_int == BANK_ROUTE_GLOBAL_LOCK_BUSY_EXIT_CODE:
        return (
            f"全局银行自动化锁被另一个 owner 持有（如来参缘定时调拨），"
            f"未启动 {bank_name} 子进程（退出码 {code_int}，非业务退出码，"
            "需人工稍后重试，不要自动强抢）"
        )
    hint = BANK_EXIT_HINTS.get(bank_name, {}).get(code_int, f"{bank_name} 子流程异常退出")
    return f"{mode_label(dry_run)}失败：{hint}（退出码 {code_int}）"


