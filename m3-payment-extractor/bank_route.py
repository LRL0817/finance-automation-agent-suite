def _truthy_form_value(form: dict, *keys: str) -> bool:
    """从 form 里任一 key 读出"显式真值"。

    用于 bank_form 内的布尔类强制开关（如 `CMB_REQUIRE_LOGIN_ACCOUNT_SELECTION` /
    `招行强制选择登录名`）。覆盖 bool / 数字 / 常见真值字符串（"1" / "true" /
    "yes" / "on" / "是" / "真"），并对其它字符串显式返回 False，避免空串或
    `"false"` 被误判为真。
    """
    for key in keys:
        if key not in form:
            continue
        raw = form.get(key)
        if isinstance(raw, bool):
            if raw:
                return True
            continue
        if isinstance(raw, (int, float)):
            if raw != 0:
                return True
            continue
        if isinstance(raw, str):
            if raw.strip().lower() in {"1", "true", "yes", "on", "是", "真"}:
                return True
    return False


# ===== 招行付款方账号尾号推导 =====
# M3/OA 抓出来的「付款账号 / 付款方账号 / 付方账号 / 付款账户 / 付款账户账号」字段
# 用于推导招行单笔转账经办页面「付款方账号」下拉里的目标尾号（3 位）。
# 不从收款字段、收款账号、收款开户行、收款银行、支行推导。
_M3_PAYER_ACCOUNT_KEYS: tuple[str, ...] = (
    "付款账号", "付款方账号", "付方账号",
    "付款账户", "付款账户账号",
    "付方账户", "付方账户账号",
    "付款人账号", "付款人账户",
)

# 人工确认的「付款单位关键词 → 招行付款方账号尾号」兜底规则。
# 仅在 form 既没有显式尾号、也没有 M3/OA 付款账号字段时使用；只看付款单位名称
# （`付款单位名称 / 付款单位`），不看任何收款字段。
# 未命中时**保持页面默认**（不写 suffix），绝不猜。
# 默认留空 —— 新增条目必须基于人工核实的「付款单位 → 实际启用的招行 001/002 账号」
# 业务事实，并在 PR 描述里写清来源；不要在仓库中提交未审计的真实账号尾号。
_CMB_PAYER_UNIT_TO_ACCOUNT_SUFFIX: tuple[tuple[str, str], ...] = ()


def _digits_only(value: object) -> str:
    return "".join(ch for ch in str(value or "") if ch.isdigit())


def _account_tail_from_m3_field(text: object, n: int = 3) -> str:
    """从 M3/OA 付款账号字段提取末尾 N 位数字。

    与下游 `ubank_common._payer_account_tail_digits` 同一套切分规则：
    - 按 `,` / `，` 取账号段（防 「账号, 公司名」 里的数字污染）；
    - 账号段数字位数 >= n 才返回末 N 位；否则 fail-closed 返回空串。
    """
    if n <= 0:
        return ""
    s = str(text or "")
    for sep in (",", "，"):
        if sep in s:
            s = s.split(sep, 1)[0]
            break
    digits = _digits_only(s)
    if len(digits) >= n:
        return digits[-n:]
    return ""


def derive_cmb_payer_account_suffix(form: dict, payer_unit: str) -> str:
    """推导招行付款方账号尾号（生产主路径）。

    优先级：
    1. form 显式尾号字段（`招行付款方账号尾号 / CMB_PAYER_ACCOUNT_SUFFIX / CMB付款方账号尾号`）；
    2. M3/OA 付款账号字段（`_M3_PAYER_ACCOUNT_KEYS` 列出的任一）—— 抽末 3 位；
    3. 已人工确认的「付款单位 → 尾号」规则表 `_CMB_PAYER_UNIT_TO_ACCOUNT_SUFFIX`。
    都未命中返回空串，调用方按「不写 suffix，保持页面默认账号」处理。

    输入 `payer_unit` 仅参与第 3 步规则匹配；绝不从收款方任何字段推导。
    """
    explicit = first_value(form, "招行付款方账号尾号", "CMB_PAYER_ACCOUNT_SUFFIX", "CMB付款方账号尾号")
    if explicit and explicit.isdigit():
        return explicit

    for key in _M3_PAYER_ACCOUNT_KEYS:
        raw = form.get(key)
        if raw is None:
            continue
        tail = _account_tail_from_m3_field(raw, 3)
        if tail:
            return tail

    if _CMB_PAYER_UNIT_TO_ACCOUNT_SUFFIX:
        payer_norm = compact(payer_unit)
        if payer_norm:
            for keyword, suffix in _CMB_PAYER_UNIT_TO_ACCOUNT_SUFFIX:
                kw = compact(keyword)
                if kw and kw in payer_norm and suffix.isdigit():
                    return suffix

    return ""


def safe_filename(value: object) -> str:
    text = str(value or "").strip()
    text = re.sub(r'[<>:"/\\|?*]+', "_", text)
    return text or "unknown"


def build_branch_queries(bank_head: str, branch_full: str) -> list[str]:
    bank_head = (bank_head or "").strip()
    branch_full = (branch_full or "").strip()
    if not branch_full:
        return [bank_head] if bank_head else []

    simplified = branch_full
    for token in ("股份有限公司", "有限责任公司", "有限公司", "股份有限", "有限"):
        simplified = simplified.replace(token, "")
    if bank_head:
        simplified = simplified.replace(bank_head, "")
    simplified = simplified.replace("支行", "").replace("分行", "").strip()

    candidates = [
        simplified,
        f"{bank_head}{simplified}" if bank_head and simplified else "",
        bank_head,
        branch_full,
    ]
    result: list[str] = []
    for item in candidates:
        item = item.strip()
        if item and item not in result:
            result.append(item)
    return result


