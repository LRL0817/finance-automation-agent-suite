def read_json(path: Path) -> object:
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def write_json(path: Path, payload: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=2)


def normalize_amount(value: object) -> str:
    return str(value or "").replace(",", "").replace("，", "").strip()


def first_value(form: dict, *keys: str) -> str:
    for key in keys:
        value = form.get(key)
        if str(value or "").strip():
            return str(value).strip()
    return ""


def normalize_usb_port(value: object, env_name: str) -> str:
    port = str(value or "").strip()
    if not port:
        return ""
    if not port.isdigit() or not 1 <= int(port) <= 30:
        raise RouteError(f"{env_name} 必须是 1-30 的数字端口，当前为: {port}")
    return str(int(port))


def resolve_m3_abc_ukey_port(form: dict) -> str:
    """Return the ABC UKey physical USBHub port for an M3-origin payer.

    This is deliberately separate from bank routing. It only answers:
    "this record is already routed to ABC; which physical ABC UKey should be
    powered?" Unknown payer means fail-closed before opening the bank.
    """
    override = (
        os.getenv("M3_ABC_UKEY_USB_PORT", "")
        or os.getenv("ABC_USB_HUB_UKEY_PORT", "")
    )
    override_port = normalize_usb_port(override, "M3_ABC_UKEY_USB_PORT/ABC_USB_HUB_UKEY_PORT")
    if override_port:
        return override_port

    payer_norm = compact(first_value(form, "付款单位名称", "付款单位"))
    if not payer_norm:
        return ""
    for keyword, port in ABC_M3_UKEY_PORT_BY_PAYER:
        if compact(keyword) in payer_norm:
            return port
    return ""


