def normalize_form(form: dict, bank: str) -> dict:
    if not isinstance(form, dict):
        raise RouteError("JSON 顶层必须是对象")

    payment_bank = canonical_bank(bank or form.get("付款银行") or form.get("付款银行原文"))
    if not payment_bank:
        raise RouteError("未识别付款银行，不能启动银行程序")

    account = compact(first_value(form, "收方账号", "acct_no", "银行账户", "收款账号", "收款方账号"))
    payee_name = first_value(form, "收方户名", "acct_name", "收款单位名称", "收款户名", "收款方户名")
    amount = normalize_amount(first_value(form, "金额", "amount", "申请金额", "转账金额"))
    original_amount = amount
    amount_override = normalize_amount(os.getenv("M3_BANK_AMOUNT_OVERRIDE", ""))
    if amount_override:
        amount = amount_override
    receive_bank = first_value(form, "开户银行", "bank", "收款方开户行", "收款银行")
    branch_full = first_value(form, "支行名称", "branch_full", "开户支行", "开户网点")
    purpose = first_value(form, "用途", "purpose", "申请说明", "备注") or "货款"
    ref = first_value(form, "业务参考号", "label", "单据编号", "合同编号")
    payer = first_value(form, "付款单位名称", "付款单位")

    errors: list[str] = []
    if not account:
        errors.append("缺少收款账号")
    elif not account.isdigit():
        errors.append(f"收款账号必须为纯数字: {account}")
    elif not (8 <= len(account) <= 32):
        errors.append(f"收款账号位数异常({len(account)}): {account}")

    if not payee_name:
        errors.append("缺少收款户名")
    if not amount:
        errors.append("缺少金额")
    else:
        try:
            amount_value = float(amount)
        except ValueError:
            errors.append(f"金额不是有效数字: {amount}")
        else:
            if amount_value <= 0:
                errors.append(f"金额必须大于 0: {amount}")
            else:
                # 生产风控可配置上限：M3_MAX_PAYMENT_AMOUNT 默认空＝只做格式校验，
                # 不限额；显式设置且为正数时，超限直接 fail-closed（不启动银行）。
                # 不硬编码任何真实金额上限，仅提供机制。
                max_cap_raw = os.getenv("M3_MAX_PAYMENT_AMOUNT", "").strip()
                if max_cap_raw:
                    try:
                        max_cap = float(normalize_amount(max_cap_raw))
                    except ValueError:
                        errors.append(
                            f"M3_MAX_PAYMENT_AMOUNT 不是有效数字: {max_cap_raw}（请修正或清空该环境变量）"
                        )
                    else:
                        if max_cap > 0 and amount_value > max_cap:
                            errors.append(
                                f"金额 {amount} 超过生产上限 {max_cap_raw}"
                                f"（M3_MAX_PAYMENT_AMOUNT）：fail-closed，不启动银行制单"
                            )

    if not receive_bank:
        errors.append("缺少收款开户银行")
    if payment_bank == "招商银行" and not payer:
        errors.append("招行制单需要付款单位名称来匹配 U 盾端口")
    if payment_bank == "兴业银行" and not branch_full:
        errors.append("兴业制单需要完整支行名称参与指纹和搜索")
    if payment_bank == "中国银行" and not (branch_full or receive_bank):
        errors.append("中行制单需要收款人开户行")
    errors.extend(validate_m3_screenshot_info(form))

    if errors:
        raise RouteError("；".join(errors))

    normalized = dict(form)
    branch_queries = form.get("branch_queries")
    if not isinstance(branch_queries, list) or not all(isinstance(x, str) for x in branch_queries):
        branch_queries = build_branch_queries(receive_bank, branch_full)

    # 招行可选字段：登录名（同一 U-BANK 下挂多账号时用），属于「双账号特殊场景」
    # 能力，**默认不写入 bank_form**：避免普通单账号公司因 form 残留登录名字段
    # 而被下拉候选读取失败卡住。
    #
    # 透传条件（任一即可）：
    #   - 源 form 显式含 CMB_REQUIRE_LOGIN_ACCOUNT_SELECTION=true；
    #   - 源 form 显式含 招行强制选择登录名=true。
    # 满足时把强制开关本身一起镜像写入归一化 bank_form，让下游 制单.py 据此决定
    # 是否注入 CMB_LOGIN_ACCOUNT_NAME；否则原 form 里的登录名字段被丢弃、不参与
    # 归一化输出。
    cmb_login_account_name_raw = first_value(form, "招行登录名", "CMB_LOGIN_ACCOUNT_NAME", "CMB登录名")
    cmb_login_force_enabled = _truthy_form_value(form, "CMB_REQUIRE_LOGIN_ACCOUNT_SELECTION", "招行强制选择登录名")
    if cmb_login_account_name_raw and cmb_login_force_enabled:
        cmb_login_account_name = cmb_login_account_name_raw
    else:
        if cmb_login_account_name_raw and not cmb_login_force_enabled:
            print(
                "[M3 路由] bank_form 含登录名字段，但未设置 CMB_REQUIRE_LOGIN_ACCOUNT_SELECTION=true/"
                "招行强制选择登录名=true，归一化时已丢弃；沿用 U-BANK 默认登录名"
            )
        cmb_login_account_name = ""

    # 招行可选字段：付款方账号下拉（单笔转账经办页面的「付款方账号」），与登录名是
    # 两条独立流程。仅做保留透传 / 由 M3 字段推导尾号，不改路由 / 金额覆盖 /
    # 提交门禁 / U 盾端口。
    #
    # 少数公司同一个 UKey 在登录窗口切换账号（例如来参缘 001/002），此时即使
    # M3 本地账户表带有「付款账号」，也必须禁止把账号末三位继续推导成制单页
    # 付款方账号下拉选择；否则会同时触发两套选择链路。
    # - 完整付款账号文本仅在 form 显式提供时透传，绝不主动从其它字段构造（生产主路径
    #   走 suffix；TEXT 仅供调试 / 兜底）。
    # - SUFFIX 走 derive_cmb_payer_account_suffix：显式字段 → M3 付款账号字段 →
    #   人工确认的付款单位规则；任一未命中返回空串，由调用方保持页面默认账号。
    cmb_disable_payer_account_selection = _truthy_form_value(
        form,
        "CMB_DISABLE_PAYER_ACCOUNT_SELECTION",
        "招行禁用付款方账号选择",
    )
    if cmb_disable_payer_account_selection:
        cmb_payer_account_text = ""
        cmb_payer_account_suffix = ""
    else:
        cmb_payer_account_text = first_value(form, "招行付款方账号", "CMB_PAYER_ACCOUNT_TEXT", "CMB付款方账号")
        cmb_payer_account_suffix = derive_cmb_payer_account_suffix(form, payer)

    normalized.update(
        {
            "付款银行": payment_bank,
            "M3合同付款列表截图": first_value(form, "M3合同付款列表截图"),
            "M3抓取详情截图": first_value(form, "M3抓取详情截图"),
            "付款单位名称": payer,
            "收方账号": account,
            "收方户名": payee_name,
            "开户银行": receive_bank,
            "支行名称": branch_full,
            "金额": amount,
            "原始金额": original_amount if amount_override else form.get("原始金额", ""),
            "金额覆盖来源": "M3_BANK_AMOUNT_OVERRIDE" if amount_override else form.get("金额覆盖来源", ""),
            "用途": purpose,
            "业务参考号": ref,
            "label": ref or form.get("label") or "default",
            "amount": amount,
            "acct_no": account,
            "acct_name": payee_name,
            "bank": receive_bank,
            "branch_full": branch_full,
            "branch_queries": branch_queries,
            "purpose": purpose,
        }
    )
    if cmb_login_account_name:
        normalized["招行登录名"] = cmb_login_account_name
        normalized["CMB_LOGIN_ACCOUNT_NAME"] = cmb_login_account_name
        # 强制开关与值一起镜像写入归一化 bank_form，让下游 制单.py 在未显式 env
        # 注入 CMB_LOGIN_ACCOUNT_NAME 时仍能据此启用登录名选择。
        normalized["CMB_REQUIRE_LOGIN_ACCOUNT_SELECTION"] = True
        normalized["招行强制选择登录名"] = True
    else:
        # 默认归一化输出：删除可能从源 form 浅拷贝过来的登录名/强制开关字段，
        # 避免单账号公司在 bank_form 残留下进入登录名选择路径。
        for _stale_key in (
            "招行登录名",
            "CMB_LOGIN_ACCOUNT_NAME",
            "CMB登录名",
            "CMB_REQUIRE_LOGIN_ACCOUNT_SELECTION",
            "招行强制选择登录名",
        ):
            normalized.pop(_stale_key, None)
    if cmb_payer_account_text:
        normalized["招行付款方账号"] = cmb_payer_account_text
        normalized["CMB_PAYER_ACCOUNT_TEXT"] = cmb_payer_account_text
    if cmb_payer_account_suffix:
        normalized["招行付款方账号尾号"] = cmb_payer_account_suffix
        normalized["CMB_PAYER_ACCOUNT_SUFFIX"] = cmb_payer_account_suffix
    if cmb_disable_payer_account_selection:
        for _stale_key in (
            "招行付款方账号",
            "CMB_PAYER_ACCOUNT_TEXT",
            "CMB付款方账号",
            "招行付款方账号尾号",
            "CMB_PAYER_ACCOUNT_SUFFIX",
            "CMB付款方账号尾号",
            "CMB_PAYER_ACCOUNT_INDEX",
        ):
            normalized.pop(_stale_key, None)
        normalized["CMB_DISABLE_PAYER_ACCOUNT_SELECTION"] = True
        normalized["招行禁用付款方账号选择"] = True
    return normalized


def load_latest_form() -> tuple[dict, Path]:
    route_paths = [
        BANK_FORMS_DIR / "latest_route.json",
        LEGACY_BANK_FORMS_DIR / "latest_route.json",
    ]
    for route_path in route_paths:
        if not route_path.exists():
            continue
        route = read_json(route_path)
        if isinstance(route, dict):
            for key in ("制单JSON", "银行JSON"):
                candidate = route.get(key)
                if candidate and Path(candidate).exists():
                    path = Path(candidate)
                    payload = read_json(path)
                    if isinstance(payload, dict):
                        return payload, path
    for path in (CURRENT_DIR / "bank_form.json", ROOT / "bank_form.json"):
        if not path.exists():
            continue
        payload = read_json(path)
        if not isinstance(payload, dict):
            raise RouteError(f"默认表单 JSON 不是对象: {path}")
        return payload, path
    raise RouteError(f"未找到默认表单 JSON: {CURRENT_DIR / 'bank_form.json'}")


def load_single_form(path_text: str | None) -> tuple[dict, Path]:
    if not path_text:
        return load_latest_form()
    path = Path(path_text)
    if not path.is_absolute():
        path = ROOT / path
    if not path.exists():
        raise RouteError(f"JSON 文件不存在: {path}")
    payload = read_json(path)
    if not isinstance(payload, dict):
        raise RouteError(f"单笔制单 JSON 必须是对象: {path}")
    return payload, path


