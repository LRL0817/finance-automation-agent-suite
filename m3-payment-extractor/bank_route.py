    retry_wait_seconds = max(0.0, env_float("BOC_ROUTE_RETRY_WAIT_SECONDS", 15.0))
    between_items_seconds = max(0.0, env_float("BOC_ROUTE_BETWEEN_ITEMS_SECONDS", 15.0))
    failures: list[tuple[int, int]] = []
